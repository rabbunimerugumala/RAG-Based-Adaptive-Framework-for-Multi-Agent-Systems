"""Answer generation backends. ONE shared generator instance serves every pipeline and agent role.

* OllamaLLM          - real mode: a local instruction-tuned model served by Ollama (GPU or CPU).
* ExtractiveGenerator - DEV MODE ONLY: deterministic sentence extraction, no language model at all.
"""

from __future__ import annotations

import json
import re
from typing import Protocol

import httpx

from adaptive_rag.schemas import Evidence, GeneratedAnswer
from adaptive_rag.text import (
    citation_refs,
    content_terms,
    focus_terms,
    keywords,
    split_sentences,
    strip_citations,
)

INSUFFICIENT_ANSWER = "The provided documents do not contain enough information to answer this question."

ANSWER_SYSTEM_PROMPT = """You are a careful research assistant. Answer the question using ONLY the numbered \
evidence passages provided. Rules:
1. Every factual sentence must end with citations to the passages that support it, e.g. [1] or [2][3].
2. Do not use outside knowledge. Do not guess.
3. If the passages do not contain the answer, set "insufficient" to true and the answer to: \
"%s"
4. Be concise: one to three complete sentences (never just a bare name or number). Begin with the direct answer.
Return JSON with keys: answer (string), citations (list of passage numbers used), insufficient (boolean).""".replace(
    "%s", INSUFFICIENT_ANSWER
)

ANSWER_SCHEMA = {
    "type": "object",
    "properties": {
        "answer": {"type": "string"},
        "citations": {"type": "array", "items": {"type": "integer"}},
        "insufficient": {"type": "boolean"},
    },
    "required": ["answer", "citations", "insufficient"],
}

REWRITE_SYSTEM_PROMPT = """You help a retrieval system search a document collection. Given a question and \
what was missing from the previous attempt, write up to 3 short, different keyword search queries that \
could find the missing information. Return JSON: {"queries": ["...", "..."]}."""

REWRITE_SCHEMA = {
    "type": "object",
    "properties": {"queries": {"type": "array", "items": {"type": "string"}, "maxItems": 3}},
    "required": ["queries"],
}


# --- Evidence Agent judge prompts -------------------------------------------------------------------
# TRIPLET: the Judge system instruction from MAIN-RAG, Appendix C (Chang et al., ACL 2025), verbatim.
JUDGE_TRIPLET_SYSTEM = (
    "You are a noisy document evaluator that can judge if the external document is noisy for the query with "
    "unrelated or misleading information. Given a retrieved Document, a Question, and an Answer generated by an "
    "LLM (LLM Answer), you should judge whether both the following two conditions are reached: (1) the Document "
    "provides specific information for answering the Question; (2) the LLM Answer directly answers the question "
    "based on the retrieved Document. Please note that external documents may contain noisy or factually "
    "incorrect information. If the information in the document does not contain the answer, you should point it "
    "out with evidence. You should answer with \"Yes\" or \"No\" with evidence of your judgment, where \"No\" "
    "means one of the conditions (1) and (2) are unreached and indicates it is a noisy document."
)
# PAIR: this project's adaptation - condition (1) only, so no per-document Predictor call is needed.
JUDGE_PAIR_SYSTEM = (
    "You are a noisy document evaluator that can judge if the external document is noisy for the query with "
    "unrelated or misleading information. Given a retrieved Document and a Question, judge whether the Document "
    "provides specific information for answering the Question. Please note that external documents may contain "
    "noisy or unrelated information. Answer with \"Yes\" or \"No\" first, where \"No\" indicates a noisy document."
)
# Predictor system instruction from MAIN-RAG, Appendix C (used in triplet mode).
PREDICTOR_SYSTEM = (
    "You are an accurate and reliable AI assistant that can answer questions with the help of external "
    "documents. You should only provide the correct answer without repeating the question and instruction."
)


def judge_user_prompt(question: str, passage: str, answer: str | None = None, max_chars: int = 1400) -> str:
    text = f"Document: {passage[:max_chars]}\n\nQuestion: {question}\n"
    if answer is not None:
        text += f"LLM Answer: {answer}\n"
    return text + "\nJudgment (Yes or No):"


class LLMError(RuntimeError):
    pass


def yes_no_score(top_logprobs: list[dict]) -> tuple[float, dict]:
    """MAIN-RAG Sec. 3.2: score = log P("Yes") - log P("No") for the first generated token.

    Token variants (" Yes", "yes", ...) are matched case-insensitively and the most likely variant is used.
    If a token is absent from the returned top-k list its log-probability is unknown; it is then bounded by
    (lowest returned log-probability - 1), and this is recorded so the approximation is visible.
    """
    yes = no = None
    for t in top_logprobs:
        tok = str(t.get("token", "")).strip().lower()
        lp = float(t.get("logprob", -1e9))
        if tok == "yes":
            yes = lp if yes is None else max(yes, lp)
        elif tok == "no":
            no = lp if no is None else max(no, lp)
    floor = min((float(t.get("logprob", 0.0)) for t in top_logprobs), default=-30.0) - 1.0
    detail = {"yes_logprob": yes, "no_logprob": no, "floor_used": yes is None or no is None}
    return (yes if yes is not None else floor) - (no if no is not None else floor), detail


def format_evidence(evidence: list[Evidence], max_chars: int = 1400) -> str:
    blocks = []
    for e in evidence:
        loc = f"{e.filename}" + (f", page {e.page}" if e.page else "")
        blocks.append(f"[{e.ref}] (source: {loc})\n{e.text[:max_chars]}")
    return "\n\n".join(blocks)


class Generator(Protocol):
    name: str
    is_llm: bool

    def answer(self, question: str, evidence: list[Evidence]) -> GeneratedAnswer: ...

    def rewrite_queries(self, question: str, missing: str) -> list[str]: ...

    def judge(self, question: str, passage: str, answer: str | None = None) -> tuple[float, dict]: ...

    def predict(self, question: str, passage: str) -> str: ...


class OllamaLLM:
    is_llm = True

    def __init__(self, url: str, model: str, num_ctx: int, max_tokens: int, timeout_s: float,
                 num_gpu: int | None = None):
        self.url, self.model, self.name = url.rstrip("/"), model, f"ollama:{model}"
        self.options = {"temperature": 0.0, "seed": 42, "num_ctx": num_ctx, "num_predict": max_tokens}
        if num_gpu is not None:
            self.options["num_gpu"] = num_gpu
        self.timeout = timeout_s

    def status(self) -> dict:
        try:
            r = httpx.get(f"{self.url}/api/tags", timeout=3)
            r.raise_for_status()
            names = [m["name"] for m in r.json().get("models", [])]
            ok = self.model in names or f"{self.model}:latest" in names
            return {"ready": ok, "detail": "model available" if ok else
                    f"Ollama is running but '{self.model}' is not pulled (run: ollama pull {self.model})"}
        except httpx.HTTPError as exc:
            return {"ready": False, "detail": f"Ollama not reachable at {self.url}: {exc.__class__.__name__}"}

    def chat_json(self, system: str, user: str, schema: dict) -> dict:
        payload = {
            "model": self.model, "stream": False, "format": schema, "options": self.options,
            "messages": [{"role": "system", "content": system}, {"role": "user", "content": user}],
        }
        try:
            r = httpx.post(f"{self.url}/api/chat", json=payload, timeout=self.timeout)
            r.raise_for_status()
        except httpx.HTTPError as exc:
            raise LLMError(f"Ollama request failed: {exc}") from exc
        content = r.json().get("message", {}).get("content", "")
        try:
            return json.loads(content)
        except json.JSONDecodeError:
            m = re.search(r"\{.*\}", content, re.S)
            if m:
                try:
                    return json.loads(m.group(0))
                except json.JSONDecodeError:
                    pass
            raise LLMError(f"Model did not return valid JSON: {content[:200]!r}") from None

    def _post_chat(self, payload: dict) -> dict:
        try:
            r = httpx.post(f"{self.url}/api/chat", json=payload, timeout=self.timeout)
            r.raise_for_status()
            return r.json()
        except httpx.HTTPError as exc:
            raise LLMError(f"Ollama request failed: {exc}") from exc
        except ValueError as exc:
            raise LLMError(f"Ollama returned invalid JSON: {exc}") from exc

    def judge(self, question: str, passage: str, answer: str | None = None) -> tuple[float, dict]:
        """One-token Yes/No judgment with log-probabilities (MAIN-RAG Agent-2). Returns (score, detail)."""
        system = JUDGE_TRIPLET_SYSTEM if answer is not None else JUDGE_PAIR_SYSTEM
        payload = {
            "model": self.model, "stream": False, "logprobs": True, "top_logprobs": 20,
            "options": {**self.options, "num_predict": 1},
            "messages": [{"role": "system", "content": system},
                         {"role": "user", "content": judge_user_prompt(question, passage, answer)}],
        }
        data = self._post_chat(payload)
        lps = data.get("logprobs") or []
        if not lps or not lps[0].get("top_logprobs"):
            raise LLMError("Ollama did not return token log-probabilities (needs a recent Ollama version)")
        score, detail = yes_no_score(lps[0]["top_logprobs"])
        detail["token"] = lps[0].get("token")
        return round(score, 4), detail

    def predict(self, question: str, passage: str) -> str:
        """Per-passage short answer (MAIN-RAG Agent-1 Predictor), used in triplet judge mode."""
        payload = {
            "model": self.model, "stream": False, "options": {**self.options, "num_predict": 48},
            "messages": [{"role": "system", "content": PREDICTOR_SYSTEM},
                         {"role": "user", "content": f"Document: {passage[:1400]}\n\nQuestion: {question}"}],
        }
        return str(self._post_chat(payload).get("message", {}).get("content", "")).strip()[:300]

    def answer(self, question: str, evidence: list[Evidence]) -> GeneratedAnswer:
        user = f"Evidence passages:\n\n{format_evidence(evidence)}\n\nQuestion: {question}"
        data = self.chat_json(ANSWER_SYSTEM_PROMPT, user, ANSWER_SCHEMA)
        text = str(data.get("answer", "")).strip()
        insufficient = bool(data.get("insufficient", False)) or not text
        cited = [int(c) for c in data.get("citations", []) if isinstance(c, (int, float))]
        for ref in citation_refs(text):  # inline markers count too
            if ref not in cited:
                cited.append(ref)
        if insufficient:
            text = INSUFFICIENT_ANSWER
            cited = []
        return GeneratedAnswer(answer=text, cited_refs=cited, insufficient=insufficient, raw=json.dumps(data))

    def rewrite_queries(self, question: str, missing: str) -> list[str]:
        data = self.chat_json(REWRITE_SYSTEM_PROMPT, f"Question: {question}\nMissing: {missing}", REWRITE_SCHEMA)
        return [q.strip() for q in data.get("queries", []) if isinstance(q, str) and q.strip()][:3]


class ExtractiveGenerator:
    """DEV MODE: picks the evidence sentences with the highest keyword overlap with the question.

    Not a language model. Its answers are copied from evidence, so verification scores in dev mode are
    optimistic by construction and must not be reported as model results.
    """

    is_llm = False
    name = "extractive-dev"

    def __init__(self, min_overlap: float = 0.5, max_sentences: int = 2):
        self.min_overlap, self.max_sentences = min_overlap, max_sentences

    def answer(self, question: str, evidence: list[Evidence]) -> GeneratedAnswer:
        q_terms = keywords(question)
        if not q_terms:
            return GeneratedAnswer(answer=INSUFFICIENT_ANSWER, cited_refs=[], insufficient=True)
        scored: list[tuple[float, int, int, str]] = []
        for e in evidence:
            for pos, sent in enumerate(split_sentences(e.text)):
                terms = set(content_terms(sent))
                overlap = sum(1 for t in q_terms if t in terms) / len(q_terms)
                scored.append((overlap, -e.ref, -pos, sent))
        focus = focus_terms(question)
        if focus:  # a sentence must mention what is being asked for (e.g. 'price')
            scored = [x for x in scored if set(focus) <= set(content_terms(x[3]))]
        scored.sort(reverse=True)
        chosen = [s for s in scored if s[0] >= self.min_overlap][: self.max_sentences]
        if not chosen:
            return GeneratedAnswer(answer=INSUFFICIENT_ANSWER, cited_refs=[], insufficient=True)
        parts, refs = [], []
        for _, neg_ref, _, sent in chosen:
            parts.append(f"{sent.rstrip()} [{-neg_ref}]")
            if -neg_ref not in refs:
                refs.append(-neg_ref)
        return GeneratedAnswer(answer=" ".join(parts), cited_refs=refs, insufficient=False)

    def rewrite_queries(self, question: str, missing: str) -> list[str]:
        return []  # dev mode relies on the planner's deterministic reformulation

    def judge(self, question: str, passage: str, answer: str | None = None) -> tuple[float, dict]:
        """DEV MODE stand-in for the LLM judge: keyword overlap mapped to a +-10 scale. Not an LLM score."""
        q_terms = keywords(question) + (keywords(answer) if answer else [])
        if not q_terms:
            return 0.0, {"dev_heuristic": True}
        terms = set(content_terms(passage))
        overlap = sum(1 for t in q_terms if t in terms) / len(q_terms)
        return round((overlap - 0.5) * 20, 4), {"dev_heuristic": True, "overlap": round(overlap, 3)}

    def predict(self, question: str, passage: str) -> str:
        e = Evidence(ref=1, chunk_id="dev", doc_id="dev", filename="dev", chunk_index=0, text=passage, rrf_score=0)
        a = self.answer(question, [e])
        return "" if a.insufficient else strip_citations(a.answer)

